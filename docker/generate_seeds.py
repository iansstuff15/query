def ddb(value):
    if value is None:
        return {"NULL": True}
    if isinstance(value, bool):
        return {"BOOL": value}
    if isinstance(value, int):
        return {"N": str(value)}
    if isinstance(value, str) and value.replace(".", "", 1).isdigit():
        return {"N": value}
    return {"S": value}
