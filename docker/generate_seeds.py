def lit(value, bool_style="true"):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        if bool_style == "int":
            return "1" if value else "0"
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def inserts(table, rows, cols, bool_style="true", ts_cols=(), ts=lambda v: v, prefix="", per_row=False, suffix=";"):
    out = []
    values = []
    for r in rows:
        vals = []
        for c in cols:
            v = r[c]
            vals.append(ts(lit(v)) if c in ts_cols and v is not None else lit(v, bool_style))
        values.append("(" + ", ".join(vals) + ")")
    if per_row:
        for v in values:
            out.append(f"{prefix}INSERT INTO {table} ({', '.join(cols)}) VALUES {v}{suffix}")
    else:
        out.append(f"{prefix}INSERT INTO {table} ({', '.join(cols)}) VALUES\n  " + ",\n  ".join(values) + suffix)
    return "\n".join(out)


