# ---------------------------------------------------------------- MongoDB
def mongo_doc(row, ts_cols=()):
    out = {}
    for k, v in row.items():
        key = "_id" if k == "id" else k
        if v is None:
            out[key] = None
        elif k in ts_cols:
            out[key] = {"$date": v.replace(" ", "T") + "Z"}
        elif k in ("price", "total", "unit_price"):
            out[key] = float(v)
        else:
            out[key] = v
